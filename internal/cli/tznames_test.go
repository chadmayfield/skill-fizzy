package cli

import (
	"archive/zip"
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"slices"
	"testing"
)

// zoneNamesFromGo reads the zone names from the zoneinfo.zip that ships
// with the Go toolchain, the file time/tzdata embeds.
func zoneNamesFromGo(t *testing.T) []string {
	t.Helper()
	path := filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip")
	r, err := zip.OpenReader(path)
	if err != nil {
		t.Skipf("no zoneinfo.zip in GOROOT: %v", err)
	}
	defer r.Close()
	var names []string
	for _, f := range r.File {
		names = append(names, f.Name)
	}
	slices.Sort(names)
	return names
}

// tzNames must match the Go toolchain's zone list. After a Go update that
// changes the list, regenerate tznames.go with
// FZ_UPDATE_TZNAMES=1 go test -run TestZoneNamesMatchGo ./internal/cli
func TestZoneNamesMatchGo(t *testing.T) {
	want := zoneNamesFromGo(t)
	if os.Getenv("FZ_UPDATE_TZNAMES") == "1" {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by TestZoneNamesMatchGo from %s's lib/time/zoneinfo.zip. DO NOT EDIT.\n\n", runtime.Version())
		b.WriteString("package cli\n\n// tzNames lists every zone in Go's embedded time zone database, sorted.\nvar tzNames = []string{\n")
		for _, n := range want {
			fmt.Fprintf(&b, "\t%q,\n", n)
		}
		b.WriteString("}\n")
		if err := os.WriteFile("tznames.go", b.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if !slices.Equal(tzNames, want) {
		t.Errorf("tzNames has %d names and Go's zoneinfo.zip has %d; regenerate tznames.go (see this test's comment)", len(tzNames), len(want))
	}
	if !slices.IsSorted(tzNames) {
		t.Error("tzNames is not sorted")
	}
}
